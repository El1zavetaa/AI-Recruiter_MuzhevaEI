"""
Шаг "дебатов" агентов (см. ТЗ: "агрегирует результаты дебатов агентов").

Технический Скринер и HR-Аналитик работают независимо друг от друга
(намеренно — чтобы оценка стека не влияла на оценку карьерной динамики
и наоборот). После того как оба вынесли независимое заключение,
подключается третья роль — Модератор: он не может добавлять новых
фактов, только видит оба заключения и явно называет, согласуются они
или противоречат друг другу — это и есть "дебаты", результат которых
затем агрегируется в отчёт (report.py).
"""
from __future__ import annotations

from .schemas import AgentFinding
from .llm_client import LLMClient

MODERATOR_SYSTEM_PROMPT = (
    "Ты — модератор, который сравнивает два независимых заключения по "
    "одному кандидату (от технического скринера и от HR-аналитика) и "
    "явно называет, согласуются они или противоречат друг другу. "
    "Не придумывай новых фактов, работай только с тем, что дано ниже."
)


def run_debate(technical: AgentFinding, hr: AgentFinding, llm: LLMClient) -> str:
    """Возвращает текст-синтез: согласие / противоречие между агентами."""
    user_prompt = (
        f"Скор Технического Скринера: {technical.score}\n"
        f"Риски по мнению Технического Скринера: {'; '.join(technical.risks) or 'нет'}\n"
        f"Скор HR-Аналитика: {hr.score}\n"
        f"Риски по мнению HR-Аналитика: {'; '.join(hr.risks) or 'нет'}\n"
    )
    return llm.complete(MODERATOR_SYSTEM_PROMPT, user_prompt)
